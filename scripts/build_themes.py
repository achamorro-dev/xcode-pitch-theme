#!/usr/bin/env python3
"""Render every supported tool from the shared Xcode Pitch palettes (stdlib only)."""

import argparse
import importlib.util
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent.parent
_spec = importlib.util.spec_from_file_location("xcode_pitch_light", ROOT / "scripts" / "build_light.py")
build_light = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(build_light)

DARK_ROLES = {
    "#000000": "background", "#dfdfdf": "foreground", "#9a9c9d": "muted",
    "#646e83": "selection", "#6699ff": "accent", "#a0d07d": "comment",
    "#fc6a5d": "string", "#d0bf69": "number", "#ff7ab2": "keyword",
    "#ffa14f": "orange", "#5dd8ff": "function", "#49b7d7": "variable",
    "#e5cfff": "type", "#a167e6": "operator", "#d0a8ff": "purple",
    "#dfdfe0": "punctuation",
}


def palettes():
    return {mode: json.loads((ROOT / "palettes" / f"{mode}.json").read_text()) for mode in ("dark", "light")}


def dump(value):
    return json.dumps(value, indent=2, ensure_ascii=False) + "\n"


def mix(a, b, weight):
    a, b = a.lstrip("#"), b.lstrip("#")
    return "#" + "".join(f"{round(int(a[i:i+2], 16) * (1-weight) + int(b[i:i+2], 16) * weight):02x}"
                         for i in (0, 2, 4))


def terminal_colors(p):
    return [p["black"],
            *[p[k] for k in ("red", "green", "yellow", "blue", "purple", "cyan")],
            p["white"], p["muted"],
            *[p[k] for k in ("red", "green", "yellow", "blue", "purple", "cyan")],
            p["brightWhite"]]


def ghostty(p):
    fields = {"background": p["background"], "foreground": p["foreground"],
              "cursor-color": p["cursor"], "cursor-text": p["background"],
              "selection-background": p["selection"], "selection-foreground": p["foreground"]}
    return ("# Generated by xcode-pitch-theme/scripts/build_themes.py\n"
            + "".join(f"{k} = {v}\n" for k, v in fields.items())
            + "".join(f"palette = {i}={v}\n" for i, v in enumerate(terminal_colors(p))))


def opencode_mode(p):
    """Complete V2 token tree; the same renderer can compose external palettes."""
    bg, fg = p["background"], p["foreground"]
    feedback = {"error": p["red"], "warning": p["yellow"], "success": p["green"], "info": p["blue"]}
    hues = {}
    for hue, color in {"gray": fg, **{k: p[k] for k in
                          ("red", "orange", "yellow", "green", "cyan", "blue", "purple")}}.items():
        hues[hue] = {str(step): mix(color, bg, (step - 100) / 850) for step in range(100, 1000, 100)}
    hues.update(accent="$hue.blue", interactive="$hue.blue", neutral="$hue.gray")
    hues["gray"].update({"200": fg, "400": p["muted"], "600": p["raised"],
                         "700": p["surface"], "800": bg, "900": bg})
    action = {k: {"base": fg, "$hovered": p["accent"], "$disabled": p["muted"]}
              for k in ("primary", "secondary", "destructive")}
    action["destructive"]["base"] = p["red"]
    return {
        "hue": hues, "categorical": ["blue", "purple", "green", "cyan", "orange"],
        "text": {"base": fg, "muted": p["muted"], "action": action,
                 "formfield": {"base": fg, "$focused": p["accent"]},
                 "feedback": {k: {"base": v} for k, v in feedback.items()}},
        "background": {"base": bg, "raised": {"base": p["surface"], "high": p["raised"], "max": p["selection"]},
                       "action": {k: {"base": "transparent", "$hovered": p["raised"], "$selected": p["selection"]}
                                  for k in ("primary", "secondary", "destructive")},
                       "formfield": {"base": p["surface"]},
                       "feedback": {k: {"base": mix(bg, v, .10)} for k, v in feedback.items()}},
        "border": {"base": p["border"]}, "scrollbar": {"base": p["muted"]},
        "diff": {"text": {"added": p["green"], "removed": p["red"], "context": fg, "hunkHeader": p["purple"]},
                 "background": {"added": mix(bg, p["green"], .12), "removed": mix(bg, p["red"], .12), "context": bg},
                 "highlight": {"added": mix(bg, p["green"], .25), "removed": mix(bg, p["red"], .25)},
                 "lineNumber": {"text": p["muted"], "background": {"added": bg, "removed": bg}}},
        "syntax": {k: p[k] for k in ("comment", "keyword", "function", "variable", "string", "number", "type", "operator", "punctuation")},
        "markdown": {k: p[v] for k, v in {
            "text": "foreground", "heading": "accent", "link": "blue", "linkText": "cyan",
            "code": "string", "blockQuote": "comment", "emphasis": "purple", "strong": "foreground",
            "horizontalRule": "muted", "listItem": "keyword", "listEnumeration": "number",
            "image": "blue", "imageText": "cyan", "codeBlock": "foreground"}.items()},
        "@dialog": {"background": {"base": "$background.raised.base"}},
    }


def opencode_theme(dark, light):
    mode = opencode_mode(dark)
    return {"base": {k: v for k, v in mode.items() if k != "hue"},
            "dark": {"hue": mode["hue"]}, "light": opencode_mode(light)}


def herdr_theme(dark, light, mode="auto"):
    if mode not in ("auto", "dark", "light"):
        raise ValueError(f"Unknown mode: {mode}")
    auto = mode == "auto"
    text = '# Generated theme fragment: merge into config.toml, preserving other tables.\n[theme]\nname = "terminal"\nauto_switch = ' + str(auto).lower() + '\n'
    if auto:
        text += 'dark_name = "terminal"\nlight_name = "terminal"\n'
    for current in (("dark", "light") if auto else (mode,)):
        p = dark if current == "dark" else light
        text += "\n[theme.custom" + (f".{current}" if auto else "") + "]\n"
        fields = {"panel_bg": "background", "sidebar_bg": "background", "text": "foreground",
                  "accent": "accent", "active_row_bg": "surface", "selection_bg": "selection",
                  "surface0": "surface", "surface1": "raised", "surface_dim": "surface",
                  "overlay0": "border", "overlay1": "muted", "subtext0": "muted",
                  "red": "red", "green": "green", "yellow": "yellow", "blue": "blue",
                  "mauve": "purple", "teal": "cyan", "peach": "orange"}
        text += "".join(f'{key} = "{p[value]}"\n' for key, value in fields.items())
    return text + "\n"


def lua(value):
    if isinstance(value, dict):
        return "{\n" + "".join(f"  [{json.dumps(k)}] = {lua(v)},\n" for k, v in value.items()) + "}"
    return json.dumps(value, ensure_ascii=False)


def dark_editor(template, palette):
    def replace(match):
        raw = match.group(1)
        color = raw.lower()
        if len(color) in (4, 5):
            color = "#" + "".join(c * 2 for c in color[1:])
        role = DARK_ROLES.get(color[:7])
        if role is None or palette[role] == color[:7]:
            return match.group()
        return json.dumps(palette[role] + color[7:])

    # The original published Dark files intentionally had no final newline.
    return re.sub(r'"(#[\da-fA-F]{3,8})"', replace, template).rstrip("\n")


def render():
    p = palettes()
    files = {}
    for mode in ("dark", "light"):
        files[f"extras/ghostty/xcode-{mode}"] = ghostty(p[mode])
    files["extras/opencode/xcode-pitch.json"] = dump(opencode_theme(p["dark"], p["light"]))
    for mode in ("auto", "dark", "light"):
        files[f"extras/herdr/{mode}.toml"] = herdr_theme(p["dark"], p["light"], mode)
    files["extras/neovim/lua/xcode_pitch/palettes.lua"] = "-- Generated; edit palettes/*.json instead.\nreturn " + lua(p) + "\n"
    for template, filename in (("dark", "Xcode Pitch Dark Theme"), ("bordered", "Xcode Pitch Dark Bordered Theme")):
        text = (ROOT / "templates" / "vscode" / f"{template}.jsonc").read_text()
        files[f"themes/{filename}-color-theme.json"] = dark_editor(text, p["dark"])
    files["themes/Xcode Pitch Light-color-theme.json"] = dump(build_light.generate(p["light"]))
    return files


def build(check=False):
    stale = []
    for relative, content in render().items():
        path = ROOT / relative
        if path.exists() and path.read_text() == content:
            continue
        if check:
            stale.append(relative)
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
    if stale:
        raise ValueError("Generated themes are stale; run npm run generate:\n" + "\n".join(stale))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        build(check=args.check)
    except ValueError as error:
        parser.exit(1, f"{error}\n")


if __name__ == "__main__":
    main()
